#!/usr/bin/env python3
"""Prepare a reproducible baseline workspace from a downloaded Kaggle notebook."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path


DEFAULT_REF = "nina2025/birdclef-2026-eos-6-bz"
NOTEBOOKS_ROOT = Path("data/external/kaggle-notebooks/notebooks")
METADATA_INDEX = Path("data/external/kaggle-notebooks/metadata/combined_index.csv")
OUTPUT_ROOT = Path("experiments/baselines")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create a reproducible baseline workspace from a Kaggle notebook ref."
    )
    parser.add_argument("--ref", default=DEFAULT_REF, help="Kaggle notebook ref (<owner>/<slug>)")
    parser.add_argument("--output-root", default=str(OUTPUT_ROOT), help="Baseline output root")
    return parser.parse_args()


def safe_ref(ref: str) -> str:
    return ref.replace("/", "_")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while True:
            chunk = f.read(1024 * 1024)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def load_index_row(ref: str) -> dict:
    if not METADATA_INDEX.exists():
        raise FileNotFoundError(f"Missing metadata index: {METADATA_INDEX}")

    with METADATA_INDEX.open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row.get("ref") == ref:
                return row
    raise ValueError(f"Ref not found in metadata index: {ref}")


def write_repro_notes(path: Path, ref: str, title: str) -> None:
    path.write_text(
        "\n".join(
            [
                f"# Baseline reproduction: {ref}",
                "",
                f"Source title: {title}",
                "",
                "## Goal",
                "Reproduce this public baseline exactly as the reference point before custom improvements.",
                "",
                "## Steps",
                "1. Review notebook code and pinned assets in this folder.",
                "2. Run the notebook logic in a controlled environment with fixed seeds.",
                "3. Export predictions and compare against the baseline output (if available).",
                "4. Record runtime and output checksums for regression tracking.",
                "",
                "## Notes",
                "- This folder is generated by `scripts/prepare_baseline_repro.py`.",
                "- Keep modifications in separate experiment folders to preserve this reference snapshot.",
                "",
            ]
        ),
        encoding="utf-8",
    )


def main() -> int:
    args = parse_args()
    ref = args.ref.strip()
    idx_row = load_index_row(ref)

    source_dir = NOTEBOOKS_ROOT / safe_ref(ref)
    if not source_dir.exists():
        raise FileNotFoundError(f"Notebook directory not found: {source_dir}")

    target_root = Path(args.output_root)
    target_dir = target_root / safe_ref(ref)
    target_dir.mkdir(parents=True, exist_ok=True)

    copied_files = []
    for src in sorted(source_dir.iterdir()):
        if not src.is_file():
            continue
        dst = target_dir / src.name
        shutil.copy2(src, dst)
        copied_files.append(
            {
                "name": src.name,
                "size_bytes": src.stat().st_size,
                "sha256": sha256(src),
            }
        )

    manifest = {
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "ref": ref,
        "title": idx_row.get("title", ""),
        "author": idx_row.get("author", ""),
        "votes": idx_row.get("votes", ""),
        "buckets": idx_row.get("buckets", ""),
        "bucket_ranks": idx_row.get("bucket_ranks", ""),
        "source_dir": str(source_dir),
        "generated_dir": str(target_dir),
        "files": copied_files,
    }
    (target_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    write_repro_notes(target_dir / "README.md", ref=ref, title=idx_row.get("title", ""))

    print(f"Prepared baseline workspace: {target_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
